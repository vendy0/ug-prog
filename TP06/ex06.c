void ft_array_cpy(int src[], int dest[], int size)
{
    int index = 0;
    for (int i = size - 1; i >= 0; i--)
    {
        dest[index++] = src[i];
        printf("%d\n", i);
    }
}

void ft_print_int_tab(int tab[], int size)
{
    if (size <= 0)
        return;

    for (int i = 0; i < size; i++)
    {
        printf("%d", tab[i]);
        if (i == size - 1)
            printf("\n");
        else
            printf(" ");
    }
}

